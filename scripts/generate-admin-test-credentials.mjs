import { randomBytes } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const DEFAULT_EMAIL = "admin-test@activora.local";
const ENV_FILE = path.join(process.cwd(), ".env.local");

function generatePassword() {
  return randomBytes(24).toString("base64url");
}

function upsertEnvVars(content, vars) {
  let result = content.endsWith("\n") ? content : `${content}\n`;

  for (const [key, value] of Object.entries(vars)) {
    const regex = new RegExp(`^${key}=.*$`, "m");
    const line = `${key}=${value}`;

    if (regex.test(result)) {
      result = result.replace(regex, line);
    } else {
      result = `${result.trimEnd()}\n${line}\n`;
    }
  }

  return result;
}

async function main() {
  const email = process.env.ADMIN_TEST_EMAIL?.trim() || DEFAULT_EMAIL;
  const password = generatePassword();

  let content = "";
  try {
    await access(ENV_FILE);
    content = await readFile(ENV_FILE, "utf8");
  } catch {
    content = "# Generated by npm run admin:regenerate-credentials\n";
  }

  const updated = upsertEnvVars(content, {
    ADMIN_TEST_EMAIL: email,
    ADMIN_TEST_PASSWORD: password,
  });

  await writeFile(ENV_FILE, updated, "utf8");

  console.log("");
  console.log("Admin test credentials written to .env.local");
  console.log("");
  console.log(`  Email:    ${email}`);
  console.log(`  Password: ${password}`);
  console.log("");
  console.log("Save this password now — it will not be shown again.");
  console.log("Restart the dev server if it is already running.");
  console.log("");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
